#!/usr/bin/env node
// make-captions.mjs: word timestamps -> styled ASS (and SRT) captions.
//
// Groups words into short on-screen chunks (max words / chars, break on
// punctuation and on pauses), never splits a word, and optionally highlights
// the word being spoken (short-form "karaoke" style). Styling comes from the
// brand pack (font, size, colors, outline, vertical margin).
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs, emit, fail, loadBrand, ensureDir, round } from './_lib.mjs';

const spec = {
  name: 'make-captions',
  summary: 'Build ASS + SRT captions from a words.json (transcribe.py output).',
  usage: ['node make-captions.mjs --words clip.words.json --out-ass clip.ass [--out-srt clip.srt] [--brand brands/example.json]'],
  options: {
    words: { required: true, desc: 'words.json with words[{word,start,end}]' },
    outAss: { desc: 'ASS output (default: <words>.ass)' },
    outSrt: { desc: 'SRT output (optional; plain chunks, no highlight)' },
    brand: { desc: 'Brand / style pack JSON (default: brands/example.json)' },
    font: { desc: 'Font family override (must be installed, or pass --fonts-dir to burn.mjs)' },
    size: { desc: 'Video canvas WxH used as the ASS PlayRes (default: brand.canvas)' },
    maxWords: { type: 'number', desc: 'Max words per chunk (default: brand.captions.maxWords)' },
    maxChars: { type: 'number', desc: 'Max characters per chunk (default: brand.captions.maxChars)' },
    pauseBreak: { type: 'number', default: 0.35, desc: 'Start a new chunk after a pause longer than this (s)' },
    uppercase: { type: 'boolean', desc: 'Force uppercase' },
    noHighlight: { type: 'boolean', desc: 'Disable active-word highlight' },
    offset: { type: 'number', default: 0, desc: 'Shift all times by this many seconds (e.g. after trimming a lead)' },
  },
  outputs: ['ASS subtitle file (burn with burn.mjs)', 'optional SRT', 'JSON summary { chunks, events }'],
  verify: 'Burn onto the clip and view frames: text inside safe area, chunks change only at word boundaries.',
};

const o = parseArgs(spec);
const brand = loadBrand(o.brand, import.meta.url);
const C = brand.captions;
const [W, H] = o.size ? o.size.split('x').map(Number) : [brand.canvas.width, brand.canvas.height];
const family = (o.font || brand.font.family || 'Sans').split(',')[0].trim();
const maxWords = o.maxWords ?? C.maxWords ?? 3;
const maxChars = o.maxChars ?? C.maxChars ?? 18;
const upper = o.uppercase || C.uppercase;

let data;
try { data = JSON.parse(fs.readFileSync(o.words, 'utf8')); } catch (e) { fail(`cannot read --words: ${e.message}`); }
const words = (data.words || [])
  .map((w) => ({ text: String(w.word ?? w.text ?? '').trim(), start: Number(w.start) + o.offset, end: Number(w.end) + o.offset }))
  .filter((w) => w.text && Number.isFinite(w.start) && Number.isFinite(w.end) && w.end > 0)
  .map((w) => ({ ...w, start: Math.max(0, w.start), text: upper ? w.text.toUpperCase() : w.text }));
if (!words.length) fail('no words in input');

// ---- chunking: only ever at word boundaries ----
const chunks = [];
let cur = [];
const flush = () => { if (cur.length) chunks.push(cur); cur = []; };
for (let i = 0; i < words.length; i++) {
  const w = words[i];
  const prev = cur[cur.length - 1];
  const len = cur.map((x) => x.text).join(' ').length;
  if (cur.length && (cur.length >= maxWords || len + 1 + w.text.length > maxChars || (prev && w.start - prev.end > o.pauseBreak))) flush();
  cur.push(w);
  if (/[.!?,;:]$/.test(w.text)) flush();
}
flush();

// ---- ASS ----
const assColor = (hex, alpha = 0) => {
  const h = String(hex).replace('#', '');
  const [r, g, b] = [h.slice(0, 2), h.slice(2, 4), h.slice(4, 6)];
  return `&H${alpha.toString(16).padStart(2, '0').toUpperCase()}${b}${g}${r}`.toUpperCase();
};
const t = (s) => {
  const cs = Math.max(0, Math.round(s * 100));
  const h = Math.floor(cs / 360000), m = Math.floor(cs / 6000) % 60, sec = Math.floor(cs / 100) % 60, c = cs % 100;
  return `${h}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}.${String(c).padStart(2, '0')}`;
};
const escAss = (s) => s.replace(/\\/g, '\\\\').replace(/\{/g, '(').replace(/\}/g, ')');
const textColor = assColor(C.textColor || '#ffffff');
const accent = assColor(brand.colors.accent || '#ffd400');
const outline = assColor(brand.colors.outline || '#000000');
const ovr = (c) => c.replace(/^&H00/, '&H') + '&'; // inline override form: &HBBGGRR&
const header = `[Script Info]
; generated by video-editing-skills make-captions.mjs
ScriptType: v4.00+
PlayResX: ${W}
PlayResY: ${H}
WrapStyle: 2
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Caption,${family},${C.fontSize},${textColor},${accent},${outline},&H80000000,-1,0,0,0,100,100,0,0,1,${C.outline},${C.shadow},2,60,60,${C.marginV},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;
const events = [];
const highlight = !o.noHighlight && C.highlightActiveWord !== false;
chunks.forEach((ch, ci) => {
  const next = chunks[ci + 1];
  const start = ch[0].start;
  // hold the chunk until the next one starts if the gap is tiny (avoids flicker), else until last word ends + 0.15s
  let end = ch[ch.length - 1].end;
  end = next && next[0].start - end < 0.3 ? next[0].start : end + 0.15;
  if (next) end = Math.min(end, next[0].start);
  if (!highlight) {
    events.push([start, end, ch.map((w) => escAss(w.text)).join(' ')]);
    return;
  }
  ch.forEach((w, wi) => {
    const s = wi === 0 ? start : w.start;
    const e = wi === ch.length - 1 ? end : ch[wi + 1].start;
    if (e - s < 0.01) return;
    const line = ch.map((x, xi) => (xi === wi ? `{\\c${ovr(accent)}}${escAss(x.text)}{\\c${ovr(textColor)}}` : escAss(x.text))).join(' ');
    events.push([s, e, line]);
  });
});
const ass = header + events.map(([s, e, txt]) => `Dialogue: 0,${t(s)},${t(e)},Caption,,0,0,0,,${txt}`).join('\n') + '\n';
const outAss = path.resolve(o.outAss || o.words.replace(/(\.words)?\.json$/i, '') + '.ass');
ensureDir(path.dirname(outAss));
fs.writeFileSync(outAss, ass);

let outSrt = null;
if (o.outSrt) {
  const st = (s) => {
    const ms = Math.max(0, Math.round(s * 1000));
    const h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, sec = Math.floor(ms / 1000) % 60;
    return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')},${String(ms % 1000).padStart(3, '0')}`;
  };
  const srt = chunks.map((ch, i) => {
    const next = chunks[i + 1];
    const end = next ? Math.min(ch[ch.length - 1].end + 0.15, next[0].start) : ch[ch.length - 1].end + 0.15;
    return `${i + 1}\n${st(ch[0].start)} --> ${st(end)}\n${ch.map((w) => w.text).join(' ')}\n`;
  }).join('\n');
  outSrt = path.resolve(o.outSrt);
  ensureDir(path.dirname(outSrt));
  fs.writeFileSync(outSrt, srt);
}

emit({ ok: true, ass: outAss, srt: outSrt, font: family, playRes: `${W}x${H}`, chunks: chunks.length, events: events.length,
  firstChunk: { start: round(chunks[0][0].start), text: chunks[0].map((w) => w.text).join(' ') } });
